-- Run as BOOK_APP. Identity columns require Oracle 12c or later.
CREATE TABLE authors (
  author_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  author_name VARCHAR2(150) NOT NULL,
  email VARCHAR2(254), country VARCHAR2(100),
  CONSTRAINT pk_authors PRIMARY KEY (author_id),
  CONSTRAINT uq_authors_email UNIQUE (email)
);
CREATE TABLE categories (
  category_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  category_name VARCHAR2(100) NOT NULL, description VARCHAR2(500),
  CONSTRAINT pk_categories PRIMARY KEY (category_id),
  CONSTRAINT uq_categories_name UNIQUE (category_name)
);
CREATE TABLE publishers (
  publisher_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  publisher_name VARCHAR2(150) NOT NULL, address VARCHAR2(300),
  contact_number VARCHAR2(30), email VARCHAR2(254),
  CONSTRAINT pk_publishers PRIMARY KEY (publisher_id),
  CONSTRAINT uq_publishers_email UNIQUE (email)
);
CREATE TABLE books (
  book_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  title VARCHAR2(250) NOT NULL,
  author_id NUMBER NOT NULL, category_id NUMBER NOT NULL, publisher_id NUMBER NOT NULL,
  isbn VARCHAR2(20) NOT NULL, price NUMBER(10,2) DEFAULT 0 NOT NULL,
  publication_year NUMBER(4), available_stock NUMBER(8) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_books PRIMARY KEY (book_id),
  CONSTRAINT uq_books_isbn UNIQUE (isbn),
  CONSTRAINT ck_books_price CHECK (price >= 0),
  CONSTRAINT ck_books_stock CHECK (available_stock >= 0),
  CONSTRAINT ck_books_year CHECK (publication_year BETWEEN 1450 AND 9999 OR publication_year IS NULL),
  CONSTRAINT fk_books_author FOREIGN KEY (author_id) REFERENCES authors(author_id),
  CONSTRAINT fk_books_category FOREIGN KEY (category_id) REFERENCES categories(category_id),
  CONSTRAINT fk_books_publisher FOREIGN KEY (publisher_id) REFERENCES publishers(publisher_id)
);
CREATE TABLE members (
  member_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  member_name VARCHAR2(150) NOT NULL, email VARCHAR2(254) NOT NULL,
  phone_number VARCHAR2(30), registration_date DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_members PRIMARY KEY (member_id),
  CONSTRAINT uq_members_email UNIQUE (email)
);
CREATE TABLE book_issues (
  issue_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  book_id NUMBER NOT NULL, member_id NUMBER NOT NULL,
  issue_date DATE DEFAULT SYSDATE NOT NULL, due_date DATE NOT NULL,
  return_date DATE, issue_status VARCHAR2(12) DEFAULT 'ISSUED' NOT NULL,
  CONSTRAINT pk_book_issues PRIMARY KEY (issue_id),
  CONSTRAINT fk_issues_book FOREIGN KEY (book_id) REFERENCES books(book_id),
  CONSTRAINT fk_issues_member FOREIGN KEY (member_id) REFERENCES members(member_id),
  CONSTRAINT ck_issues_dates CHECK (due_date >= issue_date AND (return_date IS NULL OR return_date >= issue_date)),
  CONSTRAINT ck_issues_status CHECK (issue_status IN ('ISSUED','RETURNED')),
  CONSTRAINT ck_issues_return CHECK ((issue_status = 'ISSUED' AND return_date IS NULL) OR (issue_status = 'RETURNED' AND return_date IS NOT NULL))
);
CREATE INDEX ix_books_title ON books (UPPER(title));
CREATE INDEX ix_issues_member_status ON book_issues (member_id, issue_status);
CREATE INDEX ix_issues_due ON book_issues (due_date, issue_status);

